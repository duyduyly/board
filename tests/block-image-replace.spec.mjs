import { test, expect } from '@playwright/test';

test('replacing an image preserves its properties, validates the file and respects cancel', async ({ page }) => {
  await page.goto('/');
  await page.locator('[data-template=personal]').click();
  await page.locator('[data-palette-kind=card]').click();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await page.locator('#block-editor input[type=file][accept^="image/"]').first().setInputFiles('tests/fixtures/english-endings.png');
  const image = page.frameLocator('#block-editor .gjs-frame').locator('figure img');
  await image.click();
  await page.locator('[data-image-control=alt]').fill('Diagram');
  await page.locator('[data-image-control=alt]').blur();
  await page.locator('[data-image-control=width]').fill('320');
  await page.locator('[data-image-control=width]').blur();
  const original = await image.getAttribute('src');
  const invalidChooser = page.waitForEvent('filechooser');
  await page.locator('[data-image-replace]').click();
  await (await invalidChooser).setFiles({ name: 'invalid.png', mimeType: 'image/png', buffer: Buffer.from('bad') });
  await expect(page.locator('.block-editor-notice')).not.toBeEmpty();
  expect(await image.getAttribute('src')).toBe(original);
  const chooser = page.waitForEvent('filechooser');
  await page.locator('[data-image-replace]').click();
  await (await chooser).setFiles({ name: 'replacement.gif', mimeType: 'image/gif', buffer: Buffer.from('R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7', 'base64') });
  await expect(image).toHaveAttribute('src', /^data:image\/gif;base64,/);
  await expect(image).toHaveAttribute('alt', 'Diagram');
  await expect(image).toHaveAttribute('width', '320');
  await page.locator('[data-block-label=blockUndo]').click();
  await expect(image).toHaveAttribute('src', /^data:image\/png;base64,/);
  await page.locator('[data-block-label=blockRedo]').click();
  await expect(image).toHaveAttribute('src', /^data:image\/gif;base64,/);
  await page.locator('#panel-body [type=submit]').click();
  const card = await page.evaluate(async () => (await import('/assets/js/app.js')).store.project.cards.at(-1));
  const node = card.extensions['card-atlas:document'].components[0].children.find((child) => child.tag === 'img');
  expect(card.extensions['card-atlas:images'][node.attributes.src.slice(11)].mimeType).toBe('image/gif');
  await page.locator(`[data-id="${card.id}"]`).focus();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await expect(image).toHaveAttribute('src', /^data:image\/gif;base64,/);
  await image.click();
  const chooserAgain = page.waitForEvent('filechooser');
  await page.locator('[data-image-replace]').click();
  await (await chooserAgain).setFiles('tests/fixtures/english-endings.png');
  await expect(image).toHaveAttribute('src', /^data:image\/png;base64,/);
  await page.locator('#panel-body button[type=button]').filter({ hasText: /Hủy/ }).last().click();
  const unchanged = await page.evaluate(async (id) => (await import('/assets/js/app.js')).store.project.cards.find((item) => item.id === id), card.id);
  expect(unchanged).toEqual(card);
});
