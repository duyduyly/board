import { test, expect } from '@playwright/test';
import { discardDraft } from './ui-driver.mjs';

test('insert a row at the selected cell and preserve it through save and undo', async ({ page }) => {
  await page.goto('/');
  await page.locator('[data-template=personal]').click();
  await page.locator('[data-palette-kind=card]').click();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await page.locator('[data-block-label=blockTable]').click();
  const table = page.frameLocator('#block-editor .gjs-frame').locator('table');
  await table.locator('tr').last().locator('td').first().click();
  await page.locator('[data-table-add-row]').click();
  await expect(table.locator('tr')).toHaveCount(3);
  await expect(table.locator('tr').last().locator('td')).toHaveCount(2);
  await page.locator('[data-block-label=blockUndo]').click();
  await expect(table.locator('tr')).toHaveCount(2);
  await page.locator('[data-block-label=blockRedo]').click();
  await expect(table.locator('tr')).toHaveCount(3);
  await page.locator('#panel-body [type=submit]').click();
  const card = await page.evaluate(async () => (await import('/assets/js/app.js')).store.project.cards.at(-1));
  await page.locator(`[data-id="${card.id}"]`).focus();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await expect(table.locator('tr')).toHaveCount(3);
});

test('add and remove columns and rows with undo', async ({ page }) => {
  await page.goto('/');
  await page.locator('[data-template=personal]').click();
  await page.locator('[data-palette-kind=card]').click();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await page.locator('[data-block-label=blockTable]').click();
  const table = page.frameLocator('#block-editor .gjs-frame').locator('table');
  await table.locator('td').first().click();
  await page.locator('[data-table-add-column]').click();
  for (const row of await table.locator('tr').all()) await expect(row.locator('th,td')).toHaveCount(3);
  await page.locator('[data-block-label=blockUndo]').click();
  for (const row of await table.locator('tr').all()) await expect(row.locator('th,td')).toHaveCount(2);
  await page.locator('[data-block-label=blockRedo]').click();
  for (const row of await table.locator('tr').all()) await expect(row.locator('th,td')).toHaveCount(3);
  await table.locator('td').first().click();
  await page.locator('[data-table-delete-column]').click();
  for (const row of await table.locator('tr').all()) await expect(row.locator('th,td')).toHaveCount(2);
  await page.locator('[data-block-label=blockUndo]').click();
  for (const row of await table.locator('tr').all()) await expect(row.locator('th,td')).toHaveCount(3);
  await table.locator('td').first().click();
  await page.locator('[data-table-delete-row]').click();
  await expect(table.locator('tr')).toHaveCount(1);
  await page.locator('[data-block-label=blockUndo]').click();
  await expect(table.locator('tr')).toHaveCount(2);
});

test('merged cells disable row insertion without altering their contents', async ({ page }) => {
  await page.goto('/');
  await page.locator('[data-template=personal]').click();
  await page.locator('[data-palette-kind=card]').click();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await page.locator('[data-editor-mode=html]').click();
  await page.locator('[data-editor-source]').fill('<table><tbody><tr><td colspan="2">Keep</td></tr></tbody></table>');
  await page.locator('[data-editor-mode=visual]').click();
  const table = page.frameLocator('#block-editor .gjs-frame').locator('table');
  await table.locator('td').click();
  await expect(page.locator('[data-table-add-row]')).toBeDisabled();
  await expect(page.locator('[data-table-add-row]')).toHaveAttribute('title', /ô gộp/);
  await page.locator('#panel-body [type=submit]').click();
  const card = await page.evaluate(async () => (await import('/assets/js/app.js')).store.project.cards.at(-1));
  expect(JSON.stringify(card.extensions['card-atlas:document'])).toContain('colspan');
  expect(card.content).toContain('Keep');
});

test('protects the last row and column and refuses irregular column changes', async ({ page }) => {
  await page.goto('/');
  await page.locator('[data-template=personal]').click();
  await page.locator('[data-palette-kind=card]').click();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await page.locator('[data-editor-mode=html]').click();
  const source = page.locator('[data-editor-source]');
  await source.fill('<table><tbody><tr><td>Only</td></tr></tbody></table>');
  await page.locator('[data-editor-mode=visual]').click();
  const table = page.frameLocator('#block-editor .gjs-frame').locator('table');
  await table.locator('td').click();
  await expect(page.locator('[data-table-delete-row]')).toBeDisabled();
  await expect(page.locator('[data-table-delete-column]')).toBeDisabled();
  await page.locator('[data-editor-mode=html]').click();
  await source.fill('<table><tbody><tr><td>A</td><td>B</td></tr><tr><td>C</td></tr></tbody></table>');
  await page.locator('[data-editor-mode=visual]').click();
  await table.locator('td').first().click();
  await expect(page.locator('[data-table-add-column]')).toBeDisabled();
  await expect(page.locator('[data-table-delete-column]')).toBeDisabled();
  await expect(page.locator('[data-table-add-column]')).toHaveAttribute('title', /cùng số ô/);
  await expect(table.locator('td')).toHaveCount(3);
});

test('undo restores cell content and cancel leaves the saved document unchanged', async ({ page }) => {
  await page.goto('/');
  await page.locator('[data-template=personal]').click();
  await page.locator('[data-palette-kind=card]').click();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  await page.locator('[data-editor-mode=html]').click();
  await page.locator('[data-editor-source]').fill('<table><tbody><tr><th>Header A</th><th>Header B</th></tr><tr><td>Value A</td><td>Value B</td></tr></tbody></table>');
  await page.locator('#panel-body [type=submit]').click();
  const before = await page.evaluate(async () => (await import('/assets/js/app.js')).store.project.cards.at(-1));
  await page.locator(`[data-id="${before.id}"]`).focus();
  await page.keyboard.press('Enter');
  await page.locator('#panel-tabs button').nth(1).click();
  const table = page.frameLocator('#block-editor .gjs-frame').locator('table');
  await table.locator('td').last().click();
  await page.locator('[data-table-delete-column]').click();
  await expect(table).not.toContainText('Value B');
  await page.locator('[data-block-label=blockUndo]').click();
  await expect(table.locator('td').last()).toHaveText('Value B');
  await expect(table.locator('th').last()).toHaveText('Header B');
  await table.locator('td').first().click();
  await page.locator('[data-table-delete-row]').click();
  await discardDraft(page);
  const after = await page.evaluate(async (id) => (await import('/assets/js/app.js')).store.project.cards.find((card) => card.id === id), before.id);
  expect(after).toEqual(before);
});
